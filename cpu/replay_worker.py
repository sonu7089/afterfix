"""One isolated process per versioned source tree; no external imports or model calls."""
import csv
import hashlib
import json
import pathlib
import re
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parent
METHODS = ('ordinary', 'checklist', 'provenance')
LABELS = {'ordinary':'Ordinary tools', 'checklist':'Checklist', 'provenance':'Trace access'}


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def save(path, value):
    path.write_text(json.dumps(value, indent=2)+'\n', encoding='utf-8')


def normalized(value):
    return json.loads(json.dumps(value))


def ordered(grades):
    return sorted(grades, key=lambda g:(g.get('model',''), g['id'], g.get('method','')))


def check(condition, message):
    if not condition:
        raise RuntimeError(message)


def main():
    study, dest_name = sys.argv[1:]
    folder = ROOT / 'studies' / ('v3' if study == 'cases' else study)
    dest = pathlib.Path(dest_name)
    dest.mkdir(parents=True, exist_ok=False)
    source = folder / 'source'
    sys.path.insert(0, str(source))
    from afterfix import engine, protocol_v2 as protocol
    from afterfix.heldout_cases import build, IMPLEMENTED, future_fixture
    from afterfix.heldout_grade import grade, validate_suite
    from afterfix.heldout_evaluation import evaluate
    from afterfix.runner import feedback_message
    check(pathlib.Path(engine.__file__).resolve() == source/'afterfix/engine.py', 'Incorrect source version imported')

    if study == 'cases':
        review_status = read(ROOT/'review/status.json')
        admissions = validate_suite()
        save(dest/'admission-checks.json', admissions)
        index = ['# Case review cards', '', 'All 24 cases have completed internal AI-assisted review. Independent human domain validation remains absent. Expected rows are generated by the archived Python oracle.',
                 'These answers were hidden from the model during evaluation. They are included here for scientific review.', '']
        for ident in IMPLEMENTED:
            task, private = build(ident)
            _, future_expected = future_fixture(ident, 0)
            card = [f"# {ident}: {task['title']}", '', '**Review status: internal AI review complete; evaluated fixtures accepted with documented scope.**', '',
                    'This is not independent human validation. The historical specification below is unchanged.', '',
                    'Review qualification: '+review_status[ident]['note'], '',
                    'This card shows seed 0. The source generator also supplies variants 7 and 19.', '',
                    '## Business rules', '', task['specification'], '', '## Evidence', '']
            card += ['- '+e for e in task['evidence']]
            card += ['', 'Immutable tables: '+', '.join(task['immutable_tables'])+'.',
                     'Writable projections: '+', '.join(task['writable_tables'])+'.',
                     'Full rebuilding is allowed. No append-only requirement is present.', '',
                     '## Schema and column order', '', '```sql', task['schema'], '```', '',
                     '## Visible starting data', '', '```json', json.dumps(task['tables'], indent=2), '```', '',
                     '## Oracle expected projections', '', '```json', json.dumps(private['expected'], indent=2), '```', '',
                     '## New evidence used for continuation', '', '```json', json.dumps(private['future_inputs'], indent=2), '```', '',
                     '## Expected projections after continuation', '', '```json', json.dumps(future_expected, indent=2), '```', '',
                     '## Supplied application patch', '', '```sql', task['application_sql'], '```', '',
                     '## Further reviewer notes', '', 'The completed internal decision is recorded in the package review log.', '', '- Business rules and authority:', '- Expected rows checked by hand:',
                     '- Legitimate later actions preserved:', '- Production assumptions missing:', '- Decision and reviewer/date:', '']
            (dest/(ident+'.md')).write_text('\n'.join(card), encoding='utf-8')
            index.append(f"- [{ident}: {task['title']}]({ident}.md)")
        (dest/'INDEX.md').write_text('\n'.join(index)+'\n', encoding='utf-8')
        print('PASS: 24 case admissions and 24 review cards generated.')
        return

    if study == 'diagnostic':
        public = read(folder/'raw/public-incidents.json')
        archived = read(folder/'raw/public-candidates.json')
        check(hashlib.sha256((folder/'raw/public-incidents.json').read_bytes()).hexdigest()==archived['public_source_sha256'],
              'Diagnostic public-source hash differs')
        check(hashlib.sha256((folder/'plan.md').read_bytes()).hexdigest()==archived['plan_sha256'],
              'Diagnostic plan hash differs')
        pattern = archived['pattern']
        candidates = []
        for task in public:
            sql, removed = re.subn(pattern, '', task['application_sql'], flags=re.I)
            candidates.append(dict(id=task['id'], family=task['family'], removed_clauses=removed,
                immutable_tables=task['immutable_tables'], append_only_tables=task['append_only_tables'],
                work_initial_rows=len(task['tables']['work']),
                artifact=dict(application_sql=task['application_sql'], recovery_sql=sql)))
        check(candidates == archived['cases'], 'Public-only diagnostic candidates differ')
        save(dest/'public-candidates.json', candidates)  # Saved before any private grading.
        rows = []
        for candidate in candidates:
            artifact = candidate['artifact'];ident = candidate['id']
            rows.append(dict(id=ident, family=candidate['family'], removed_clauses=candidate['removed_clauses'],
                scope_adaptation=grade(ident, artifact),
                patch_only=grade(ident, dict(artifact, recovery_sql=artifact['application_sql'])),
                no_op=grade(ident, dict(artifact, recovery_sql='SELECT 1;'))))
        check(rows == read(folder/'expected/grades.json'), 'Diagnostic grades differ from archived evidence')
        compact = {key:dict(full=sum(r[key]['complete'] for r in rows),
            executable=sum(r[key]['sql_executed'] for r in rows),
            stable=sum(r[key]['components']['repeatable'] for r in rows))
            for key in ('scope_adaptation', 'patch_only', 'no_op')}
        check(compact == read(folder/'expected/summary.json')['candidates'], 'Diagnostic totals differ')
        save(dest/'grades.json', rows);save(dest/'summary.json', compact)
        lines = ['## Post hoc CPU diagnostic', '', 'Chosen after inspecting tasks and model outcomes. Not pooled with model runs.', '',
                 '| Rule | Full recovery | Stable |', '|---|---:|---:|']
        for key, row in compact.items():
            lines.append(f"| {key} | {row['full']}/24 | {row['stable']}/24 |")
        (dest/'table.md').write_text('\n'.join(lines)+'\n', encoding='utf-8')
        save(dest/'validation.json', dict(status='passed', cases=24, rules=3, seeds=[0,7,19],
            exact_case_rule_grade_matches=72, public_candidates_exact=True, post_hoc=True, model_attempts=0))
        print('PASS: diagnostic candidates rebuilt and 72 case/rule grades match exactly.')
        return

    config = read(folder/'study.json');plan = read(folder/'plan.json')
    groups = {}
    for entry in config['raw_agents']:
        agent = read(folder/entry['file'])
        check(agent['status']=='completed', 'Agent stage not completed')
        groups.setdefault(entry['model'], []).extend(agent['runs'])
    expected_grades = read(folder/'expected/grades.json')
    grades = [];replays = [];summary = {};run_rows = [];analyses = {}
    for model, runs in groups.items():
        schedule = config['schedule'] if study=='h08' else [dict(id=b['id'],method=m)
            for batch in plan['batches'] for b in batch['blocks'] for m in b['methods']]
        check([dict(id=r['id'],method=r['method']) for r in runs] == schedule, 'Run schedule mismatch')
        check(len({(r['id'],r['method']) for r in runs}) == len(runs), 'Duplicate model attempt')
        for run in runs:
            ident, method = run['id'], run['method']
            task, _ = build(ident);view = protocol.public_task(task)
            check(run['status']=='completed', 'Incomplete model attempt')
            check(run['public_task_sha256']==protocol.digest(view), 'Public task hash mismatch')
            check(run['system_prompt_sha256']==protocol.digest(protocol.system_prompt(method)), 'System prompt hash mismatch')
            check(len(run['turns']) <= protocol.BUDGET['max_turns'], 'Turn budget exceeded')
            charged = 0;artifact = None;artifact_turn = None
            for index, turn in enumerate(run['turns'], 1):
                check(turn['turn']==index, 'Turn index mismatch')
                charged += turn['output_tokens']
                check(turn['input_tokens']<=protocol.BUDGET['max_input_tokens'], 'Recorded input budget exceeded')
                check(turn['output_tokens']<=protocol.BUDGET['max_generated_tokens_per_call'], 'Recorded output budget exceeded')
                if turn.get('rejected_after_deadline'):
                    continue
                try:
                    action, normalization = protocol.parse_response(turn['response'], method)
                except (ValueError, TypeError) as exc:
                    feedback = dict(error_type='protocol', error=str(exc),
                        instruction='Return exactly one complete JSON action. This turn was consumed.')
                    name = 'protocol_error'
                else:
                    name = action['action']
                    if name in ('test','submit'):
                        action['application_sql'] = view['application_sql']
                        artifact = {k:action[k] for k in ('application_sql','recovery_sql')};artifact_turn = index
                    check(action==turn['parsed_action'] and normalization==turn['normalization'], 'Parsed action mismatch')
                    if name == 'submit':
                        check(index==len(run['turns']) and run['stop_reason']=='submitted', 'Submission stop mismatch')
                        break
                    try:
                        if name=='query':
                            db = engine.materialize(view)
                            try:feedback = engine.run_sql(db, view, action['sql'], readonly=True)
                            finally:db.close()
                        elif name=='test':
                            feedback = engine.public_check(view, action['application_sql'], action['recovery_sql'])
                        else:
                            feedback = protocol.trace(view, action['roots'], action['direction'])
                    except Exception as exc:
                        feedback = dict(error_type='tool', error=str(exc))
                check(normalized(feedback)==turn['feedback'], f'{study}/{model}/{ident}/{method}/{index}: feedback differs (check Python/SQLite versions)')
                message = feedback_message(feedback, dict(turns=run['turns'][:index], generated_tokens=charged))
                check(message==turn['feedback_message'], 'Feedback envelope mismatch')
                replays.append(dict(model=model,id=ident,method=method,turn=index,action=name,exact=True))
            check(charged==run['generated_tokens']<=protocol.BUDGET['max_generated_tokens_per_case'], 'Token accounting mismatch')
            check(artifact==run['artifact'] and artifact_turn==run['artifact_turn'], 'Final artifact selection mismatch')
            run_rows.append(dict(model=model,id=ident,method=method,turns=len(run['turns']),
                output_tokens=charged,wall_seconds=run['wall_seconds'],stop_reason=run['stop_reason'],
                trace_calls=sum(t.get('action')=='trace' for t in run['turns']),
                time_cutoff_calls=sum(t.get('request_time_cutoff',False) for t in run['turns']),
                token_cutoff_calls=sum(t.get('reached_token_limit',False) for t in run['turns'])))
        if study == 'h08':
            scores = [dict(grade(r['id'],r['artifact']),method=r['method'],harness_version='afterfix-harness-v2') for r in runs]
            model_summary = None
        else:
            scores, model_summary = evaluate(plan, runs)
            check(model_summary['comparison_ready'], 'Missing scheduled observations')
            archived_summary = read(folder/'expected/summary.json')
            archived_analysis = archived_summary if study=='original' else archived_summary['by_model'][model]
            check(all(value==archived_analysis[key] for key,value in model_summary.items()),
                  'Regenerated family/component/paired-method analysis differs')
            analyses[model] = model_summary
            if study=='v3':
                for score in scores:score['model']=model
        grades.extend(scores)
        summary[model] = dict(by_method={},families=model_summary['by_method'] if model_summary else None)
        for method in METHODS:
            chosen=[g for g in scores if g['method']==method]
            summary[model]['by_method'][method]=dict(n=len(chosen),full=sum(g['complete'] for g in chosen),
                visible=sum(g.get('variants',[{}])[0].get('complete',False) for g in chosen),
                executable_wrong=sum(g['outcome']=='executable_but_wrong' for g in chosen),
                outcomes={o:sum(g['outcome']==o for g in chosen) for o in ('complete','executable_but_wrong','sql_execution_failure','no_valid_artifact')},
                stable=sum(g.get('components',{}).get('repeatable',False) for g in chosen))
    check(ordered(grades)==ordered(expected_grades), study+': exact grades differ from archived analysis')
    if study=='v3':
        paired={}
        for method in METHODS:
            a={g['id']:g['complete'] for g in grades if g['method']==method and g['model']=='31b'}
            b={g['id']:g['complete'] for g in grades if g['method']==method and g['model']=='12b'}
            paired[method]=dict(only_31b=[i for i in sorted(a) if a[i] and not b[i]],only_12b=[i for i in sorted(a) if b[i] and not a[i]],
                both=[i for i in sorted(a) if a[i] and b[i]],neither=[i for i in sorted(a) if not a[i] and not b[i]])
        save(dest/'paired-model-comparison.json', paired)
    save(dest/'grades.json',grades);save(dest/'summary.json',summary)
    if analyses:save(dest/'analysis.json',analyses)
    save(dest/'feedback-replays.json',replays);save(dest/'recorded-resources.json',run_rows)
    fields=['model','id','method','family','complete','visible','outcome']
    with (dest/'case-results.csv').open('w',encoding='utf-8',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=fields);writer.writeheader()
        for g in grades:writer.writerow(dict(model=g.get('model',next(iter(groups))),id=g['id'],method=g['method'],family=g['family'],
            complete=g['complete'],visible=g.get('variants',[{}])[0].get('complete',False),outcome=g['outcome']))
    lines=['## '+config['title'],'',config['caveat'],'','| Model / method | Full recovery | Visible | Executable but wrong |','|---|---:|---:|---:|']
    for model, ms in summary.items():
        for method,row in ms['by_method'].items():
            lines.append(f"| {model} / {LABELS[method]} | {row['full']}/{row['n']} | {row['visible']}/{row['n']} | {row['executable_wrong']}/{row['n']} |")
    (dest/'table.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    save(dest/'validation.json',dict(status='passed',study=study,model_attempts=len(grades),exact_grade_matches=len(grades),
        exact_feedback_replays=len(replays),source_engine=str((source/'afterfix/engine.py').relative_to(ROOT)).replace('\\','/'),
        source_engine_sha256=hashlib.sha256((source/'afterfix/engine.py').read_bytes()).hexdigest(),
        sqlite=sqlite3.sqlite_version,model_generation_repeated=False,all_studies_separate=True))
    print(f'PASS: {study}: {len(grades)} exact grades, {len(replays)} exact feedback replays.')


if __name__=='__main__':
    main()
